#!/usr/bin/env python3
"""Regenerate the files that are derived from onmodel/taxonomy.py and onmodel/data/starter-recipes.yaml.

    python scripts/sync_generated.py            write them
    python scripts/sync_generated.py --check    exit 1 if any of them is out of date (used by the tests and the CI)

Derived files:
    schemas/*.json                                   JSON Schemas for the checklist, the judgment record, the cases and the run record
    skills/fidelity-check/scripts/vocab.py           the vocabulary, so the skill's scorer can run on its own (standard library only)
    skills/fidelity-check/references/rubric.md       the nine questions, the points, the defect codes
    skills/shoot-brief/references/recipes.md         the starter recipe rules, as text an agent can read
    spec/rubric.md, spec/failure-taxonomy.md         the normative rubric and the defect codes
    ATTRIBUTION.md                                   authors, licenses and sources of the benchmark photos (from bench/cases.yaml)
"""
from __future__ import annotations

import json
import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from onmodel import schemas  # noqa: E402
from onmodel.analyze import TAG_HELP  # noqa: E402
from onmodel.recipes import load_recipes  # noqa: E402
from onmodel.taxonomy import ANSWERS, DEFECTS, DIMENSIONS, FIDELITY_ITEMS, ITEMS, OTHER_ITEMS, QUESTIONS, RISK_TAGS, SUBCATEGORIES, VETO_CODES  # noqa: E402

GENERATED = "GENERATED by scripts/sync_generated.py. Do not edit; change onmodel/taxonomy.py or the starter recipes and run the script."


def _clean(s: str) -> str:
    return " ".join(str(s).split())


def vocab_py() -> str:
    def lit(name, value):
        return f"{name} = {pprint.pformat(value, width=140, sort_dicts=False)}\n"

    parts = [f'"""{GENERATED}"""\n']
    parts += [lit("FIDELITY_ITEMS", FIDELITY_ITEMS), lit("OTHER_ITEMS", OTHER_ITEMS), "ITEMS = FIDELITY_ITEMS + OTHER_ITEMS\n",
              lit("DIMENSIONS", DIMENSIONS), lit("ANSWERS", ANSWERS), lit("QUESTIONS", QUESTIONS), lit("DEFECTS", DEFECTS), lit("VETO_CODES", VETO_CODES)]
    return "\n".join(parts)


def rubric_md(spec: bool = False) -> str:
    """The rubric for an agent skill (spec=False) or the normative spec/rubric.md (spec=True)."""
    from onmodel.judge import RUBRIC_VERSION

    title = f"# Rubric, version {RUBRIC_VERSION}" if spec else "# Rubric"
    where = "`onmodel/scoring.py`" if spec else "`scripts/score.py`"
    L = [f"<!-- {GENERATED} -->", title, "",
         f"A reviewer answers nine questions about one result photo. The questions never change. Points are computed from the answers by {where}.", "",
         "## The nine questions", "", "| Item | Dimension | Question |", "|---|---|---|"]
    for k in ITEMS:
        L.append(f"| `{k}` | {'fidelity' if k in FIDELITY_ITEMS else k} | {QUESTIONS[k]} |")
    L += ["", "## Answers and points", "", "| Answer | Points | Use it when |", "|---|---|---|",
          "| `same` | 2 | nothing is wrong |", "| `minor` | 1 | the difference is visible but does not damage the photo |",
          "| `different` | 0 | the difference is clear |", "| `cannot_tell` | 1 | you cannot see enough to decide. On a product-fidelity item it blocks Verified; on any other item it costs one point |",
          "| `not_applicable` | 2 | the question does not apply (for example, no pose reference was given) |", "",
          "## Dimensions and the verdict", "",
          f"Product fidelity is the lowest of its five items ({', '.join(f'`{k}`' for k in FIDELITY_ITEMS)}), so it is 2 only when all five are `same`. "
          f"The other items ({', '.join(f'`{k}`' for k in OTHER_ITEMS)}) are one dimension each. Five dimensions of 0 to 2 give a total out of 10.", "",
          "**Verified** = product fidelity 2 / 2, and total at least 8, and no veto defect.", "",
          "## Defect codes", "", "List every problem you found with one of these codes. A veto code blocks Verified whatever the points say.", "",
          "| Code | Item | Veto | Meaning |", "|---|---|---|---|"]
    for code, d in DEFECTS.items():
        L.append(f"| `{code}` | `{d['item']}` | {'yes' if d['veto'] else 'no'} | {d['meaning']} |")
    L += ["", f"Veto codes: {', '.join(f'`{c}`' for c in VETO_CODES)}.", ""]
    if spec:
        L += ["## Status and versioning", "",
              f"This is a draft ({RUBRIC_VERSION}). The point values, the minimum total of 8 and the list of veto codes are starting values: they have not been calibrated "
              "against human labels yet (see [calibration](../docs/calibration.md)). Any change to them raises `rubric_version`, and every judgment record carries the version "
              "it was scored with, so results are only comparable within one version.", "",
              "See also [verified](verified.md), [failure taxonomy](failure-taxonomy.md), [judge protocol](judge-protocol.md) and [hard rules](hard-rules.md).", ""]
    return "\n".join(L)


def failure_taxonomy_md() -> str:
    L = [f"<!-- {GENERATED} -->", "# Failure taxonomy", "",
         "Every problem a reviewer finds is recorded with one of these codes, so results can be counted and compared. A code belongs to one of the nine checklist items. "
         "Codes marked as veto block Verified whatever the points say.", "",
         "| Code | Item | Veto | What it means | What usually helps |", "|---|---|---|---|---|"]
    for code, d in DEFECTS.items():
        L.append(f"| `{code}` | `{d['item']}` | {'yes' if d['veto'] else 'no'} | {d['meaning']} | {d['advice']} |")
    L += ["", f"There are {len(DEFECTS)} codes, {len(VETO_CODES)} of them veto codes. The list is part of the rubric version: adding, removing or changing the veto status of a code raises `rubric_version`.", ""]
    return "\n".join(L)


def attribution_md() -> str:
    import yaml

    cases = yaml.safe_load((ROOT / "bench" / "cases.yaml").read_text(encoding="utf-8"))["cases"]
    L = [f"<!-- {GENERATED} -->", "# Attribution", "",
         "Photos used by the benchmark. Bundled photos are in this repository. Linked photos are downloaded from their source by `onmodel bench fetch` and are never committed.", "",
         "## Bundled in this repository (CC0 or public domain)", "", "| Case | Product | Author | License | Source |", "|---|---|---|---|---|"]
    for c in cases:
        s = c["source"]
        if s["kind"] == "bundled":
            L.append(f"| {c['id']} | {c['name']} | {s.get('author') or 'unknown'} | {s['license']} | [page]({s['page']}) |")
    L += ["", "## Linked, not copied", "",
          "These photos are shared under CC BY-SA. We link to them and record the sha256 of the file we measured; `onmodel bench fetch` refuses a file that no longer matches.", "",
          "| Case | Product | Author | License | Source | sha256 of the source file |", "|---|---|---|---|---|---|"]
    for c in cases:
        s = c["source"]
        if s["kind"] == "linked":
            L.append(f"| {c['id']} | {c['name']} | {s.get('author') or 'unknown'} | {s['license']} | [page]({s['page']}) | `{s['sha256_source'][:16]}...` |")
    L += ["", "## Pose photos and generated photos", "",
          "The pose reference photos in `bench/poses/` and the photos in `bench/runs/mini-test-v0.1/images/` were generated by us with gemini-nano-banana-2.1 on 2026-11-10. "
          "The people in them are synthetic adults, not real people. The generated photos start from the CC0 or public-domain product photos above. "
          "We dedicate both sets to the public domain under CC0 1.0, to the extent any rights exist. The generation prompt of every pose photo is recorded in `bench/ASSETS.json`.", "",
          "## Figures", "",
          "The figures in `docs/img/` are licensed under CC BY 4.0. Their sources are in `docs/img/src/`.", "",
          "## Trademarks", "",
          "Product names and logos that are visible in the photos (for example Labello) belong to their owners. They appear only to identify the products that were checked. No endorsement is implied.", ""]
    return "\n".join(L)


def recipes_md() -> str:
    r = load_recipes()
    L = [f"<!-- {GENERATED} -->", f"# Starter recipes (version {r['version']})", "",
         "These are the prompts of our mini test, as data. They are a baseline, not tuned prompts. The task shape is: Image 1 is the product photo, "
         "Image 2 is a pose reference photo (a person posing with some other product or outfit), and the engine swaps the product.", "",
         "## How a prompt is assembled", "",
         "1. The **header**, with `{verb}` set to `wear` or `hold`.",
         "2. For the generic variant `v0`, the **v0 tail**. For `v1`, the **v1 lead**, then one **rule** per risk tag the product has (in the order below), then the **always** rule.",
         "3. For products that carry text, an optional second pass with the **repair** prompt on the first result.", "",
         "## Header", "", f"> {_clean(r['header'])}", "", "## v0 tail", "", f"> {_clean(r['v0_tail'])}", "", "## v1 lead", "", f"> {_clean(r['v1_lead'])}", "",
         "## Rules by risk tag", "", "| Tag | Use it when | Rule |", "|---|---|---|"]
    for tag in r["rules"]:
        L.append(f"| `{tag}` | {TAG_HELP.get(tag, '')} | {_clean(r['rules'][tag])} |")
    L += ["", "## Always", "", f"> {_clean(r['always'])}", "", "## Repair (second pass for text)", "", f"> {_clean(r['repair'])}", "",
          "## Starting points by sub-category", "", "| Sub-category | Verb | Tags to start from |", "|---|---|---|"]
    for sub in SUBCATEGORIES:
        d = r["subcategories"][sub]
        L.append(f"| {sub} | {d['verb']} | {', '.join(d['tags']) or 'none'} |")
    L += ["", "## What is not a prompt rule", "",
          "- Products with small print: render at 2K or higher. In our mini test 1K gave unreadable small print in 8 of 8 photos and 2K in 0 of 4 (preliminary, see docs/mini-test.md).",
          "- Fingers over a label, and a hem that follows the pose reference instead of the product, are fixed by choosing the pose, not by rewording.", ""]
    return "\n".join(L)


def build() -> dict:
    out = {f"schemas/{name}": json.dumps(fn(), indent=2, ensure_ascii=False) + "\n" for name, fn in schemas.ALL.items()}
    out["skills/fidelity-check/scripts/vocab.py"] = vocab_py()
    out["skills/fidelity-check/references/rubric.md"] = rubric_md()
    out["skills/shoot-brief/references/recipes.md"] = recipes_md()
    out["spec/rubric.md"] = rubric_md(spec=True)
    out["spec/failure-taxonomy.md"] = failure_taxonomy_md()
    out["ATTRIBUTION.md"] = attribution_md()
    return out


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for rel, text in build().items():
        path = ROOT / rel
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if stale:
        print("out of date: " + ", ".join(stale) + "\nrun: python scripts/sync_generated.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
